#!/usr/bin/env bash
# Builds the Ethereum contracts and writes ShieldedPool's ABI to the frontend
# (apps/frontend/src/lib/abi/shielded-pool.ts, committed so the frontend
# builds without Foundry). Rerun after any change to ShieldedPool's interface.
set -euo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO/contracts/ethereum"
forge build >&2
OUT="$REPO/apps/frontend/src/lib/abi/shielded-pool.ts"
mkdir -p "$(dirname "$OUT")"
node -e '
const abi = JSON.parse(require("fs").readFileSync(process.argv[1], "utf8")).abi;
process.stdout.write("// Generated by scripts/build/export-abi.sh from contracts/ethereum. Do not edit.\n" +
  "export const shieldedPoolAbi = " + JSON.stringify(abi, null, 2) + " as const\n");
' out/ShieldedPool.sol/ShieldedPool.json > "$OUT"
echo "$OUT"
