#!/usr/bin/env node
// Constraint-removal check for the bridge circuits. For each entry of
// mutations.json: copy the circuit sources, remove one constraint, compile the
// circuit with circom, and run the named test against the mutant
// (ZKROSS_ARTIFACTS). The test must FAIL. Writes a Markdown report.
//
// Run inside WSL after scripts/build/sync-spp.sh and a normal circuit build
// (the circomlib checkout and the test binary are reused):
//   node scripts/circuits/mutate.mjs [--only O1,I3] [--report out.md]
import { execSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const only = args.includes("--only") ? args[args.indexOf("--only") + 1].split(",") : null;
const reportPath = args.includes("--report") ? args[args.indexOf("--report") + 1] : path.join(here, "mutation-report.md");
const build = process.env.ZKROSS_BUILD ?? path.join(os.homedir(), "zkross-build");
const spp = path.join(build, "spp");
const src = path.join(spp, "circuits", "src");

const { mutations } = JSON.parse(fs.readFileSync(path.join(here, "mutations.json"), "utf8"));
const results = [];

function replaceNth(text, find, replace, n) {
  let idx = -1;
  for (let i = 0; i < n; i++) {
    idx = text.indexOf(find, idx + 1);
    if (idx < 0) return null;
  }
  return text.slice(0, idx) + replace + text.slice(idx + find.length);
}

for (const m of mutations) {
  if (only && !only.includes(m.id)) continue;
  const work = fs.mkdtempSync(path.join(os.tmpdir(), `mut-${m.id}-`));
  const msrc = path.join(work, "src");
  fs.cpSync(src, msrc, { recursive: true, filter: (p) => !p.includes(`${path.sep}test${path.sep}`) });
  const file = path.join(msrc, m.file);
  const before = fs.readFileSync(file, "utf8");
  const after = replaceNth(before, m.find, m.replace, m.occurrence ?? 1);
  if (after === null) {
    results.push({ ...m, outcome: "ERROR: pattern not found" });
    continue;
  }
  fs.writeFileSync(file, after);

  const out = path.join(work, "out");
  fs.mkdirSync(out);
  const compile = spawnSync("circom", [path.join(msrc, `${m.stem}.circom`), "--r1cs", "--wasm", "-l", msrc, "-o", out], {
    encoding: "utf8",
  });
  if (compile.status !== 0) {
    results.push({ ...m, outcome: `ERROR: mutant does not compile: ${compile.stderr.split("\n").slice(0, 3).join(" ")}` });
    continue;
  }
  fs.renameSync(path.join(out, `${m.stem}_js`, `${m.stem}.wasm`), path.join(out, `${m.stem}.wasm`));

  const test = spawnSync(
    "cargo",
    ["test", "-q", "-p", "circuits", "--release", `test::prove_bridge::tests::${m.test}`, "--", "--exact"],
    { cwd: spp, encoding: "utf8", env: { ...process.env, ZKROSS_ARTIFACTS: out } }
  );
  const ran = /1 passed|1 failed/.test(test.stdout);
  const failed = test.status !== 0 && /1 failed/.test(test.stdout);
  results.push({ ...m, outcome: !ran ? `ERROR: test did not run (${test.stderr.split("\n").slice(-3).join(" ")})` : failed ? "test FAILS (good)" : "test still passes (BAD)" });
  console.log(`${m.id}\t${results.at(-1).outcome}\t${m.test}`);
  fs.rmSync(work, { recursive: true, force: true });
}

const ok = results.filter((r) => r.outcome === "test FAILS (good)").length;
const lines = [
  "# Constraint-removal check",
  "",
  `Generated by \`scripts/circuits/mutate.mjs\`. ${ok} of ${results.length} mutants make their test fail.`,
  "",
  "| ID | Circuit | Constraint (plain words) | Removal | Test | Result |",
  "| --- | --- | --- | --- | --- | --- |",
  ...results.map(
    (r) =>
      `| ${r.id} | ${r.stem} | ${r.what} | \`${m(r.find)}\` → ${r.replace ? `\`${m(r.replace)}\`` : "deleted"} | \`${r.test}\` | ${r.outcome} |`
  ),
  "",
];
function m(s) {
  return s.trim().replace(/\n\s*/g, " ").replace(/\|/g, "\\|");
}
fs.writeFileSync(reportPath, lines.join("\n"));
console.log(`\n${ok}/${results.length} mutants caught; report: ${reportPath}`);
process.exit(ok === results.length ? 0 : 1);
